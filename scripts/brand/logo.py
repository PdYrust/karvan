"""Generates the Karvan mark: an eight-pointed Persian star (khatam) cut by
a route, with saffron dashes along the route.

The flat logo, the favicon, the README image and the 3D logo all come from
the polygons written here, so they always match.

Needs shapely (pip install shapely==2.1.2). Run from the repo root:
    python scripts/brand/logo.py
"""

import json
import math
from pathlib import Path

from shapely import affinity
from shapely.geometry import LineString, MultiPolygon, Point, Polygon
from shapely.ops import substring, unary_union

SIZE = 200
CENTER = (100.0, 100.0)
RADIUS = 84.0
CORNER = 1.4  # slightly softened tile corners; rounder reads as a "verified" badge
ROUTE_WIDTH = 17.0
DASH, GAP, DASH_WIDTH = 9.0, 7.0, 4.2
MARGIN = 13.0  # keep dashes this far inside the star edge

FIROUZEH = "#17777a"
SAFFRON = "#e19a2c"
SAFFRON_ON_DARK = "#f0b04a"
FIROUZEH_ON_DARK = "#4fb8b2"


def star() -> Polygon:
    square = Polygon([(-1, -1), (1, -1), (1, 1), (-1, 1)])
    square = affinity.scale(square, RADIUS / math.sqrt(2), RADIUS / math.sqrt(2), origin=(0, 0))
    both = unary_union([square, affinity.rotate(square, 45, origin=(0, 0))])
    both = affinity.translate(both, *CENTER)
    return both.buffer(-CORNER, join_style="round").buffer(CORNER, join_style="round")


def bezier(p0, p1, p2, p3, steps=48):
    out = []
    for i in range(steps + 1):
        t = i / steps
        u = 1 - t
        out.append((
            u**3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t**3 * p3[0],
            u**3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t**3 * p3[1],
        ))
    return out


def route() -> LineString:
    a = bezier((40, 156), (78, 146), (88, 112), (100, 100))
    b = bezier((100, 100), (112, 88), (122, 54), (160, 44))
    pts = a + b[1:]

    def extend(p, q, by=40):
        dx, dy = p[0] - q[0], p[1] - q[1]
        n = math.hypot(dx, dy)
        return (p[0] + dx / n * by, p[1] + dy / n * by)

    return LineString([extend(pts[0], pts[1])] + pts + [extend(pts[-1], pts[-2])])


def dashes(center: LineString, inside: Polygon) -> list[Polygon]:
    usable = center.intersection(inside.buffer(-MARGIN))
    if usable.geom_type != "LineString":
        usable = max(usable.geoms, key=lambda g: g.length)
    out, pos = [], 0.0
    while pos + DASH <= usable.length:
        seg = substring(usable, pos, pos + DASH)
        out.append(seg.buffer(DASH_WIDTH / 2, cap_style="round", quad_segs=6))
        pos += DASH + GAP
    return out


def rings(geom) -> list[list[list[float]]]:
    polys = geom.geoms if isinstance(geom, MultiPolygon) else [geom]
    out = []
    for p in polys:
        p = p.simplify(0.12, preserve_topology=True)
        coords = list(p.exterior.coords)[:-1]
        out.append([[round(x, 2), round(y, 2)] for x, y in coords])
    return out


def path_d(rings_: list[list[list[float]]]) -> str:
    return " ".join("M" + " L".join(f"{x} {y}" for x, y in r) + "Z" for r in rings_)


def svg(star_d: str, dash_d: str, star_fill: str, dash_fill: str, size: int) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" width="{size}" height="{size}">'
        f'<path fill="{star_fill}" d="{star_d}"/><path fill="{dash_fill}" d="{dash_d}"/></svg>\n'
    )


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    shape = star()
    center = route()
    pieces = shape.difference(center.buffer(ROUTE_WIDTH / 2, cap_style="flat"))
    marks = unary_union(dashes(center, shape))

    data = {"viewBox": SIZE, "star": rings(pieces), "dashes": rings(marks), "outline": rings(shape)}
    ts = (
        "// Generated by scripts/brand/logo.py. Do not edit by hand.\n"
        "export type Ring = readonly (readonly [number, number])[];\n\n"
        f"export const viewBox = {SIZE};\n\n"
        f"export const starRings: readonly Ring[] = {json.dumps(data['star'])};\n\n"
        f"export const dashRings: readonly Ring[] = {json.dumps(data['dashes'])};\n\n"
        "// The whole star without the road cut; the 3D logo uses it as the road bed.\n"
        f"export const outlineRings: readonly Ring[] = {json.dumps(data['outline'])};\n"
    )
    (root / "web/src/components/brand/logo-geometry.ts").write_text(ts)

    star_d, dash_d = path_d(data["star"]), path_d(data["dashes"])
    (root / "web/public/favicon.svg").write_text(svg(star_d, dash_d, FIROUZEH, SAFFRON, 32))
    brand = root / "docs/brand"
    brand.mkdir(parents=True, exist_ok=True)
    (brand / "karvan-mark.svg").write_text(svg(star_d, dash_d, FIROUZEH, SAFFRON, 128))
    (brand / "karvan-mark-dark.svg").write_text(svg(star_d, dash_d, FIROUZEH_ON_DARK, SAFFRON_ON_DARK, 128))
    print(f"star pieces: {len(data['star'])}, dashes: {len(data['dashes'])}")


if __name__ == "__main__":
    main()
