// Builds the land mask for the spinning globe on the sign-in page: rows of
// latitude, each with runs of land dots. The page draws the dots itself, so it
// ships no map code and only a few KB of data.
//
// Run from the repo root (node_modules is git-ignored):
//   npm i --prefix scripts/brand --no-save --no-package-lock d3-geo@3.1.1 topojson-client@3.1.0 world-atlas@2.0.2
//   node scripts/brand/globe.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const land = feature(require('world-atlas/land-110m.json'), 'land');

// Degrees between dots along a meridian. Rows run from 80 S to 80 N.
const step = 1.6;
const rows = [];
let count = 0;
for (let lat = -80; lat <= 80.001; lat += step) {
  // Fewer dots toward the poles keeps the spacing even on the sphere.
  const slots = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / step));
  const runs = [];
  let start = -1;
  for (let i = 0; i <= slots; i++) {
    const on = i < slots && geoContains(land, [-180 + (i * 360) / slots, lat]);
    if (on && start < 0) start = i;
    if (!on && start >= 0) {
      runs.push(start, i - start);
      count += i - start;
      start = -1;
    }
  }
  rows.push([slots, ...runs]);
}

const out = new URL('../../web/src/features/login/globe-land.ts', import.meta.url);
writeFileSync(
  out,
  '// Generated by scripts/brand/globe.mjs from Natural Earth (public domain) land.\n' +
    `// Rows of latitude from -80 to 80 every ${step} degrees. Each row is\n` +
    '// [slots around the row, start, length, start, length, ...] for its land runs.\n' +
    `export const landStep = ${step};\n` +
    `export const landRows: readonly (readonly number[])[] = ${JSON.stringify(rows)};\n`,
);
console.log('land dots', count, 'rows', rows.length);
