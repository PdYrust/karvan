// Draws the dotted globe behind the sign-in page: land as dots, centered on
// Iran, with a dashed route between two servers. Writes a static SVG so the
// page ships no map code or map data.
//
// Run from the repo root (node_modules is git-ignored):
//   npm i --prefix scripts/brand --no-save --no-package-lock d3-geo@3.1.1 topojson-client@3.1.0 world-atlas@2.0.2
//   node scripts/brand/globe.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoContains, geoDistance, geoOrthographic } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const land = feature(require('world-atlas/land-110m.json'), 'land');

const size = 1000;
const center = [53, 32]; // Iran
const projection = geoOrthographic()
  .rotate([-center[0], -center[1]])
  .translate([size / 2, size / 2])
  .scale(size / 2 - 4);

// The two ends of the route: a server in Europe and one in Iran.
const ends = { from: [8.7, 50.1], to: [51.4, 35.7] };

const visible = (p) => geoDistance(p, center) < Math.PI / 2 - 0.02;
const fmt = (n) => n.toFixed(1);

function dots(step, test) {
  const out = [];
  for (let lat = -84; lat <= 84; lat += step) {
    const lonStep = step / Math.max(Math.cos((lat * Math.PI) / 180), 0.2);
    for (let lon = -180; lon < 180; lon += lonStep) {
      const p = [lon, lat];
      if (!visible(p) || !test(p)) continue;
      const [x, y] = projection(p);
      // Dots shrink toward the rim, like a sphere seen from the front.
      const r = 1.2 + 2.2 * Math.cos(geoDistance(p, center));
      out.push(`<circle cx="${fmt(x)}" cy="${fmt(y)}" r="${fmt(r)}"/>`);
    }
  }
  return out.join('');
}

const landDots = dots(1.5, (p) => geoContains(land, p));
const seaDots = dots(3.6, (p) => !geoContains(land, p));

// The route bows away from the surface, like a flight path on a map.
const [ax, ay] = projection(ends.from);
const [bx, by] = projection(ends.to);
const lift = 0.35 * Math.hypot(bx - ax, by - ay);
const [cx, cy] = [(ax + bx) / 2 + ((by - ay) / Math.hypot(bx - ax, by - ay)) * lift, (ay + by) / 2 - ((bx - ax) / Math.hypot(bx - ax, by - ay)) * lift];
const route = `M${fmt(ax)} ${fmt(ay)}Q${fmt(cx)} ${fmt(cy)} ${fmt(bx)} ${fmt(by)}`;

const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" fill="#fff">` +
  `<circle cx="500" cy="500" r="${size / 2 - 4}" fill="none" stroke="#fff" stroke-opacity=".18" stroke-width="2"/>` +
  `<g fill-opacity=".14">${seaDots}</g><g fill-opacity=".62">${landDots}</g>` +
  `<path d="${route}" fill="none" stroke="#fff" stroke-width="5" stroke-linecap="round" stroke-dasharray="1 13"/>` +
  `</svg>\n`;

const pct = (p) => projection(p).map((v) => +((v / size) * 100).toFixed(2));
const root = new URL('../../web/src/features/login/', import.meta.url);
writeFileSync(new URL('globe.svg', root), svg);
writeFileSync(
  new URL('globe-points.ts', root),
  '// Generated by scripts/brand/globe.mjs. Positions in percent of the globe image.\n' +
    `export const routeFrom = ${JSON.stringify(pct(ends.from))} as const;\n` +
    `export const routeTo = ${JSON.stringify(pct(ends.to))} as const;\n`,
);
console.log('globe.svg', (svg.length / 1024).toFixed(0), 'KB');
